import type { LutData } from '../types';
import { uid } from './grade';

/** Parse an Adobe/Resolve .cube 3D LUT */
export function parseCube(text: string, fallbackName: string): LutData {
  let size = 0;
  let title = '';
  const values: number[] = [];
  const lines = text.split(/\r?\n/);
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const parts = line.split(/\s+/);
    const key = parts[0].toUpperCase();
    if (key === 'TITLE') {
      title = line.slice(5).trim().replace(/^"|"$/g, '');
      continue;
    }
    if (key === 'LUT_3D_SIZE') {
      size = parseInt(parts[1], 10);
      continue;
    }
    if (key === 'LUT_1D_SIZE') throw new Error('1D LUTs are not supported — please use a 3D .cube LUT');
    if (key === 'DOMAIN_MIN' || key === 'DOMAIN_MAX' || key === 'LUT_3D_INPUT_RANGE') continue;
    if (parts.length >= 3 && /^[-+.\d]/.test(parts[0])) {
      values.push(parseFloat(parts[0]), parseFloat(parts[1]), parseFloat(parts[2]));
    }
  }
  if (!size || size < 2 || size > 129) throw new Error('Missing or invalid LUT_3D_SIZE');
  const expected = size * size * size * 3;
  if (values.length < expected) throw new Error(`LUT data incomplete (${values.length / 3} of ${expected / 3} entries)`);
  const data = new Float32Array(expected);
  for (let i = 0; i < expected; i++) data[i] = Number.isFinite(values[i]) ? values[i] : 0;
  return { id: uid(), name: title || fallbackName, size, data };
}

/** Build .cube text from GPU readback (rows: x = r + b*N, y = g) */
export function buildCube(title: string, size: number, rgba: Float32Array | Uint8Array): string {
  const isByte = rgba instanceof Uint8Array;
  const out: string[] = [
    `TITLE "${title.replace(/"/g, "'")}"`,
    '# Generated by Chroma Studio',
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0.0 0.0 0.0',
    'DOMAIN_MAX 1.0 1.0 1.0',
    '',
  ];
  const W = size * size;
  const f = (v: number) => {
    const n = isByte ? v / 255 : v;
    return Math.min(1, Math.max(0, n)).toFixed(6);
  };
  for (let b = 0; b < size; b++)
    for (let g = 0; g < size; g++)
      for (let r = 0; r < size; r++) {
        const i = (g * W + b * size + r) * 4;
        out.push(`${f(rgba[i])} ${f(rgba[i + 1])} ${f(rgba[i + 2])}`);
      }
  return out.join('\n') + '\n';
}
